#include <iostream>
#include <locale.h>
#include <stdlib.h>  // Для rand()
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    int n;
    cout << "Введите размер массива: ";
    cin >> n;

    int a[100]; // Массив 

    // 1) Формирование массива с помощью rand()
    for (int i = 0; i < n; ++i) {
        a[i] = rand() % 101 - 50; // Числа от -50 до 50
    }

    // 2) Распечатать полученный массив
    cout << "Исходный массив: ";
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    // 3) Удалить первый элемент с заданным значением
    int target;
    cout << "\nВведите значение, которое нужно удалить: ";
    cin >> target;

    bool f = false;
    for (int i = 0; i < n; ++i) {
        if (a[i] == target) {
            // Сдвигаем элементы влево, затирая найденный
            for (int j = i; j < n - 1; ++j) {
                a[j] = a[j + 1];
            }
            n--; // Уменьшаем размер
            f = true;
            cout << "Первое вхождение числа " << target << " удалено.\n";
            break; // Выходим, так как удаляем только ПЕРВЫЙ
        }
    }
    if (!f) {
        cout << "Элемент со значением " << target << " не найден.\n";
    }

    cout << "Массив после удаления: ";
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    // 4) Сдвинуть массив циклически на K элементов вправо
    int k;
    cout << "\nВведите K (на сколько элементов сдвинуть вправо): ";
    cin >> k;

    // Защита от деления на ноль, если вдруг массив стал пустым после удаления
    if (n > 0) {
        k = k % n; // Оптимизация: если сдвиг больше длины, берем остаток

        if (k > 0) {
            int temp[100]; // Временный массив для сохранения

            // Сохраняем последние K элементов
            for (int i = 0; i < k; ++i) {
                temp[i] = a[n - k + i];
            }

            // Сдвигаем первые элементы вправо
            for (int i = n - 1; i >= k; --i) {
                a[i] = a[i - k];
            }

            // Возвращаем сохраненные элементы в начало
            for (int i = 0; i < k; ++i) {
                a[i] = temp[i];
            }
        }
    }

    // 5) Распечатать полученный массив
    cout << "Массив после сдвига вправо на " << k << ": ";
    for (int i = 0; i < n; ++i) {
        cout << a[i] << " ";
    }
    cout << endl;

    return 0;
}