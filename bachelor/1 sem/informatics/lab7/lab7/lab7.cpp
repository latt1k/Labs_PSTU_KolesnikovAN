#include <iostream>
#include <locale.h>

using namespace std;

// 1) Перегруженная функция для десятичных дробей
void add(double a, double b) {
    cout << "Результат: " << a << " + " << b << " = " << (a + b) << endl;
}

// 2) Перегруженная функция для обыкновенных дробей
// Выводим результат просто как десятичное число
void add(int num1, int den1, int num2, int den2) {
    // (double) нужно, чтобы при делении не отбрасывалась дробная часть
    double res = (double)num1 / den1 + (double)num2 / den2;

    // Для красоты выводим саму операцию и сразу ответ числом
    cout << "Результат: " << num1 << "/" << den1 << " + " << num2 << "/" << den2 << " = " << res << endl;
}

int main() {
    setlocale(LC_ALL, "Russian");

    cout << "=== Десятичные дроби ===" << endl;
    double d1, d2;
    cout << "Введите две десятичные дроби: ";
    cin >> d1 >> d2;
    add(d1, d2); // Вызов первой функции

    cout << "\n=== Обыкновенные дроби ===" << endl;
    int n1, m1, n2, m2;
    cout << "Введите числитель и знаменатель 1-й дроби (через пробел): ";
    cin >> n1 >> m1;
    cout << "Введите числитель и знаменатель 2-й дроби (через пробел): ";
    cin >> n2 >> m2;

    add(n1, m1, n2, m2); // Вызов второй функции

    return 0;
}